def label_words(rng, n):
    """Return ``n`` distinct multi-word labels composed from the word banks.

    Labels read like option text on a decision form ("provisional release only",
    "escalate after a documented review"). Composition is random but bounded: once the
    random patterns stop producing new labels the function falls back to walking a
    shuffled modifier and noun grid, so any ``n`` up to that grid's size is satisfiable.
    """
    if n <= 0:
        return []
    out, seen = [], set()
    attempts = 0
    budget = 60 * n + 200
    while len(out) < n and attempts < budget:
        attempts += 1
        text = pick(rng, _LABEL_PATTERNS).format(
            mod=pick(rng, MODIFIERS),
            mod2=pick(rng, MODIFIERS),
            noun=pick(rng, NOUNS),
            noun2=pick(rng, NOUNS),
            verb=pick(rng, VERBS),
            verb2=pick(rng, VERBS),
        )
        words = text.split()
        if len(words) < 2 or len(set(words)) != len(words):
            continue
        if text in seen:
            continue
        seen.add(text)
        out.append(text)
    if len(out) < n:
        grid = [(m, h) for m in MODIFIERS for h in NOUNS]
        rng.shuffle(grid)
        for m, h in grid:
            if len(out) >= n:
                break
            text = "%s %s" % (m, h)
            if text in seen:
                continue
            seen.add(text)
            out.append(text)
    return out


