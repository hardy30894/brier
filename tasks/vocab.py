"""Vocabulary bank for the synthetic question-type generator.

This module is data, not behaviour. It supplies the raw material a generator needs to
invent thousands of *distinct* decision question types over synthetic records: a wide set
of business and technical domains (each with an entity, a typed attribute schema and
narrative sentence templates), word banks for composing option labels and instructions,
sentence frames for asking a decision, ordered scales, and frames for true/false claims.

Nothing here is imported from outside the standard library, and every helper takes an
explicit ``random.Random`` so a generator run is reproducible from a seed.

Attribute shape::

    {"key": "dock_door", "label": "dock door", "kind": "categorical", "values": [...]}
    {"key": "weight_kg", "label": "gross weight", "kind": "number", "range": [1, 900], "unit": "kg"}
    {"key": "is_hazmat", "label": "hazardous goods", "kind": "bool"}
    {"key": "handler_note", "label": "handler note", "kind": "text", "phrases": [...]}
"""

import random


def _cat(key, label, *values):
    return {"key": key, "label": label, "kind": "categorical", "values": list(values)}


def _num(key, label, lo, hi, unit):
    return {"key": key, "label": label, "kind": "number", "range": [lo, hi], "unit": unit}


def _bool(key, label):
    return {"key": key, "label": label, "kind": "bool"}


def _txt(key, label, *phrases):
    return {"key": key, "label": label, "kind": "text", "phrases": list(phrases)}


def _dom(name, entity, attributes, notes):
    return {"name": name, "entity": entity, "attributes": attributes, "notes": notes}


