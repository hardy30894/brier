def pick(rng, seq):
    """Return one element of ``seq`` using the supplied ``random.Random``."""
    items = list(seq)
    if not items:
        raise ValueError("cannot pick from an empty sequence")
    return items[rng.randrange(len(items))]


def sample(rng, seq, k):
    """Return ``k`` distinct elements of ``seq`` in random order.

    If ``k`` is at least the length of ``seq`` the whole sequence comes back shuffled,
    so callers can ask for more than is available without special-casing it.
    """
    items = list(seq)
    if k <= 0:
        return []
    if k >= len(items):
        rng.shuffle(items)
        return items
    return rng.sample(items, k)


